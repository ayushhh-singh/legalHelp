#!/usr/bin/env node
/**
 * Concatenates the OFL text and copyright line shipped with every @fontsource
 * package we bundle into public/OFL.txt, so the licence travels with the fonts
 * in dist/ as the SIL Open Font License requires.
 *
 * Idempotent, offline, and committed output — the same shape as
 * scripts/generate-icons.mjs. Re-run after changing a font dependency:
 *
 *   pnpm fonts:licenses
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const PACKAGES = [
  { name: '@fontsource-variable/inter', family: 'Inter' },
  { name: '@fontsource/poppins', family: 'Poppins' },
  { name: '@fontsource/noto-sans-devanagari', family: 'Noto Sans Devanagari' },
]

const sections = PACKAGES.map(({ name, family }) => {
  const text = readFileSync(resolve(root, 'node_modules', name, 'LICENSE'), 'utf8').trim()
  return `${'='.repeat(78)}\n${family} — bundled from ${name}\n${'='.repeat(78)}\n\n${text}\n`
})

const header = `Font licences for Sahayak
GENERATED by scripts/collect-font-licenses.mjs — do not edit by hand.

Every webfont this app ships is self-hosted from an @fontsource package and is
licensed under the SIL Open Font License 1.1. The full text and the copyright
line for each family follow. No font is ever fetched from a third party at
runtime; see tests/no-external-urls.test.ts.

`

writeFileSync(resolve(root, 'public/OFL.txt'), header + sections.join('\n'), 'utf8')
console.log(`OFL.txt written for ${PACKAGES.length} families`)
