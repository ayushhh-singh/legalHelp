/**
 * Modify by instruction — "make para 3 firmer", "shorten to one page",
 * "translate to Hindi and keep the citations in English".
 *
 * ### It returns a PROPOSAL, never a document
 *
 * The model is handed the officer's document and returns a whole new body. This
 * file never gives that body to anybody. It diffs it against what the officer
 * has (`src/lib/drafting/proposal.ts`), enforces the scope in code, evaluates
 * the checklist over the result, and returns a list of decisions. Nothing is
 * applied until the officer accepts a change, and an accepted set creates a
 * version — so the state before the change is recoverable even after they say
 * yes.
 *
 * That is a stronger guarantee than the drafting agent's, and it is the right
 * one for the difference between the two features: `runDraftingAgent` completes
 * a form the officer is still filling in, while this one CHANGES writing they
 * have already finished.
 *
 * ### Scope is the app's decision, not the model's
 *
 * A scoped instruction ("rewrite this paragraph") tells the model which block,
 * and then {@link runModifyAgent} discards every change outside it and reports
 * what it discarded. The prompt asks for the same thing, and the prompt is not
 * the enforcement — a persona instruction is not a check (ADR-036's lesson,
 * applied to a different failure). The test that matters is the one where a
 * mock returns a document with an out-of-scope block changed and the run comes
 * back with that change gone and a sentence saying so.
 *
 * ### The checklist is evaluated here, over the result
 *
 * The same rule as ADR-032 §1: whatever the agent says about its own output is
 * re-derived in code. A rewrite that reads better and fails `paraNumbering` is
 * a rewrite the officer needs told about BEFORE they accept it, and the model
 * reporting its own checklist is reporting an intention.
 *
 * ### The rationale may not name a paragraph number
 *
 * The prompt says so, and there are two independent reasons — the second is the
 * one worth knowing, because the first would look like a workaround on its own.
 *
 * The real reason is that a paragraph number in this app is GENERATED BY
 * POSITION (`renderDoc.ts`, and the defect `versions.ts#linesOf` was written to
 * fix). A proposal is a set of accept/reject controls, so accepting an
 * insertion renumbers everything below it — and a rationale that said
 * "paragraph 3 has been made firmer" is then talking about a paragraph the
 * officer never touched. Opening words are stable; a position is not.
 *
 * The second reason is that it would fail the run anyway.
 * `context.ts#NUMBERED_PROVISION_PATTERN` matches `para(graph)?\s*N` as a claim
 * about a provision, so "paragraph 3" in an answer that cites no snippet
 * containing a 3 is rejected as an invented citation — the same wall
 * `docs/DATA-GAPS.md` #60 records for the drafting agent, hit from a new
 * direction. `modify.test.ts` asserts the failure rather than leaving it to be
 * discovered, because the failure is loud and the cause is not obvious.
 */

const AGENT_ID = 'doc-modify' as const

/*
  The quick actions and the phase list live in `./modify-actions`, and are
  re-exported here so an existing import of this module keeps working.

  They moved because `ModifyPanel` needs them as VALUES, and a static import of
  this file from the panel defeats `useModifyAi`'s dynamic import of it — which
  is the property that keeps the agent, the renderer, the checklist evaluator
  and zod off the device of a reader who never turns AI on. That file has the
  full note.
*/
