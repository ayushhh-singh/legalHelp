export interface DocComment {
  id: string
  docId: string
  /**
   * Which block the comment is anchored to — the index in the body's own
   * `content` array.
   *
   * An index rather than a node id, because Tiptap does not give nodes stable
   * ids and adding one would put a field in the stored document that only
   * comments read. The cost is that a comment anchored to paragraph 4 follows
   * position 4 rather than the sentence, and `blockText` is stored beside it so
   * a comment whose paragraph has moved can still be shown with the words it
   * was about — the same "keep the quote" rule `resolveAnchor` follows for a
   * Library highlight (ADR-039 §1).
   */
  blockIndex: number
  blockText: string
  text: string
  resolved: boolean
  createdAt: string
  updatedAt: string
}

/** A comment whose block still says what it said. */
export const commentIsAnchored = (comment: DocComment, body: BodyDoc, lang: Lang = 'en'): boolean => {
  const lines = linesOfNodes(projectBody(body, lang))
  return lines[comment.blockIndex] === comment.blockText
}
